"""Pinned GNU gettext tools from https://github.com/petrprikryl/gettext.

The statically linked binaries are downloaded on the first run into the hook's
environment (``sys.prefix``), which pre-commit keeps and caches, and every binary
is checked against its SHA-256.
"""

import hashlib
import os
import platform
import shutil
import sys
import tarfile
import tempfile
import urllib.request
from pathlib import Path

GETTEXT_RELEASE = "0.0.3"  # tag of petrprikryl/gettext, GNU gettext 0.26
ARCHIVE_URL = f"https://github.com/petrprikryl/gettext/archive/refs/tags/{GETTEXT_RELEASE}.tar.gz"
# the tag archive itself is generated by GitHub and may change, the binaries may not
SHA256 = {
    "msgattrib": "623f517bc07003ccc97ad9dfa9d85cc8229b47efa9003e393ca5aa1e7dc196e8",
    "msgfmt": "0a8cff91303048b4a67e7db6de7d9cd62b0d5d0efe5513c65c81dcab3ade3f76",
    "msgmerge": "4f0b4ce5e0393937cda58c6ec2ac68d2e8443c3a6338863e8077af636f909f9f",
    "msguniq": "d53e0d0cce51dcd134ab599dd23ccab90fa3f0511ef73ff8e2c7235cf1dfaf69",
    "xgettext": "3754aa3d00fc9bbeb8f98cd676e939f5c5e07256e4bd6e0ba161111a0e396427",
}


def supported():
    return sys.platform == "linux" and platform.machine() == "x86_64"


def sha256(path):
    digest = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def complete(directory):
    return all((directory / tool).is_file() for tool in SHA256)


def bin_dir():
    """Directory with the pinned tools, downloaded when missing."""
    target = Path(sys.prefix) / f"gettext-{GETTEXT_RELEASE}"
    if complete(target):
        return target

    # GETTEXT_HOOKS_ARCHIVE_URL points to a mirror of the tag archive (e.g. a `file://` URL offline)
    url = os.environ.get("GETTEXT_HOOKS_ARCHIVE_URL", ARCHIVE_URL)
    print(f"gettext-hooks: downloading GNU gettext tools from {url}", file=sys.stderr)
    with tempfile.TemporaryDirectory(dir=sys.prefix) as tmp:
        archive = Path(tmp) / "gettext.tar.gz"
        with urllib.request.urlopen(url, timeout=60) as response, archive.open("wb") as f:
            shutil.copyfileobj(response, f)
        extracted = Path(tmp) / "bin"
        extracted.mkdir()
        with tarfile.open(archive) as tar:
            for member in tar.getmembers():
                name = Path(member.name)
                if member.isfile() and name.parent.name == "x86_64-linux" and name.name in SHA256:
                    with tar.extractfile(member) as src, (extracted / name.name).open("wb") as dst:
                        shutil.copyfileobj(src, dst)
        for tool, expected in SHA256.items():
            path = extracted / tool
            if not path.is_file():
                raise RuntimeError(f"{tool} is missing in {url}")
            if sha256(path) != expected:
                raise RuntimeError(f"{tool} from {url} does not match its SHA-256")
            path.chmod(0o755)
        # a complete copy is never replaced, another first run of the hook may be using it
        if not complete(target):
            shutil.rmtree(target, ignore_errors=True)
            try:
                extracted.rename(target)
            except OSError:
                # another first run was faster, its copy is verified the same way
                if not complete(target):
                    raise
    return target
